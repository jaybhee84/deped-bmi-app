create policy "BMI users create permitted enrolment" on public.sbfp_enrolment
  for insert to authenticated
  with check (public.is_bmi_manager() or school_id::text = public.current_bmi_school_id());
create policy "BMI users update permitted enrolment" on public.sbfp_enrolment
  for update to authenticated
  using (public.is_bmi_manager() or school_id::text = public.current_bmi_school_id())
