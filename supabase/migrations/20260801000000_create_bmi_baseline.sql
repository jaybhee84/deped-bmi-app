  username text not null unique,
  email text not null unique,
  lastname text not null,
  firstname text not null,
  middleinitial text,
  fullname text not null,
  role text not null check (role in ('school', 'division')),
  position text not null,
  created_at timestamptz not null default now(),
  school_id text references public.schools(school_id) on update cascade,
  school_name text,
  constraint bmi_profiles_reserved_creator_usernames check (
    lower(username) not in ('admin', 'admin1')
    or (
      lower(username) = 'admin1'
      and lower(trim(email)) = 'jaybhee84@gmail.com'
      and role = 'division'
    )
    or (
      lower(username) = 'admin'
      and lower(trim(email)) = 'jl3hee@gmail.com'
      and role = 'school'
    )
  )
);

create table if not exists public.students (
  id text primary key default gen_random_uuid()::text,
  lrn text,
  grade_level text,
  section text,
  adviser_name text,
  family_name text,
  first_name text,
  middle_name text,
  birthdate date,
  age integer,
  sex text,
  tribe text,
  religion text,
  is_4ps boolean default false,
  father_name text,
  mother_name text,
  guardian_name text,
  contact_number text,
  address text,
  reading_level text,
