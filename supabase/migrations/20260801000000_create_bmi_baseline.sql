  for select to public using (bucket_id in ('profiles', 'school-logo'));
create policy "Authenticated uploads BMI images" on storage.objects
  for insert to authenticated with check (bucket_id in ('profiles', 'school-logo'));
create policy "Authenticated updates BMI images" on storage.objects
  for update to authenticated
  using (bucket_id in ('profiles', 'school-logo'))
  with check (bucket_id in ('profiles', 'school-logo'));

