create index if not exists students_school_year_school_id_idx
  on public.students (school_year, school_id);

create table if not exists public.sbfp_config (
  id text primary key,
  config jsonb not null default '{}'::jsonb,
  grades text[] not null default '{}'::text[],
  criteria text[] not null default '{}'::text[],
  criteriongraderestrictions jsonb not null default '{}'::jsonb,
  set_by text,
  set_at timestamptz default timezone('utc', now()),
  "setBy" text,
  "setAt" timestamptz default timezone('utc', now())
);

create table if not exists public.sbfp_enrolment (
  id bigint generated by default as identity primary key,
  school_id varchar not null references public.schools(school_id) on update cascade,
  sy varchar not null,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  total bigint default 0,
  unique (school_id, sy)
);

create table if not exists public.school_info_sbmi (
  id text primary key,
  school_id text not null,
  school_name text not null,
  school_year text,
  vaccine_program text,
  section text,
  region text,
  province text,
  city_municipality text,
  barangay text,
  district text,
  vaccination_date date,
  supervisor text,
  vaccinator_1 text,
  vaccinator_2 text,
  vax1_received integer,
  vax1_used integer,
  vax1_unused integer,
  vax2_received integer,
  vax2_used integer,
  vax2_unused integer,
  student_rows jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists school_info_sbmi_school_id_idx
  on public.school_info_sbmi (school_id);

create table if not exists public.user_presence (
  user_id uuid not null references auth.users(id) on delete cascade,
  app_id text not null check (app_id in ('report', 'portal', 'media', 'bmi', 'admin')),
  email text,
  status text not null default 'online' check (status in ('online', 'offline')),
  last_seen timestamptz not null default now(),
  primary key (user_id, app_id)
);

create or replace function public.current_bmi_school_id()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select school_id from public.bmi_profiles where id = auth.uid();
$$;

create or replace function public.is_bmi_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select role = 'division' from public.bmi_profiles where id = auth.uid()), false);
$$;

create or replace function public.get_email_by_username(lookup_username text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select email from public.bmi_profiles
  where lower(username) = lower(trim(lookup_username))
  limit 1;
$$;

create or replace function public.dashboard_login_email(candidate_username text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select email from public.bmi_profiles
  where lower(username) = lower(trim(candidate_username))
  limit 1;
$$;

create or replace function public.is_app_email_allowed(app_key text, candidate_email text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select lower(trim(app_key)) = 'bmi'
    and candidate_email is not null
    and exists (
      select 1 from public.bmi_allowed_users
      where lower(email) = lower(trim(candidate_email))
    );
$$;

create or replace function public.ensure_owner_app_access(app_key text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  owner_email constant text := 'jaybhee84@gmail.com';
  signed_in_email text;
begin
  if lower(trim(app_key)) <> 'bmi' then
    raise exception 'Unknown application';
  end if;

  select lower(email) into signed_in_email from auth.users where id = auth.uid();
  if signed_in_email is distinct from owner_email then return false; end if;

  insert into public.bmi_profiles
    (id, username, email, lastname, firstname, middleinitial, fullname, role, position)
  values
    (auth.uid(), 'owner.jaybhee84', owner_email, 'BAZAN', 'JONYBHEE', 'A',
     'JONYBHEE A. BAZAN', 'division', 'System Owner')
  on conflict (id) do update
    set email = excluded.email, role = 'division', position = 'System Owner';
  return true;
end;
$$;

grant execute on function public.get_email_by_username(text) to anon, authenticated;
grant execute on function public.dashboard_login_email(text) to anon, authenticated;
grant execute on function public.is_app_email_allowed(text, text) to anon, authenticated;
grant execute on function public.ensure_owner_app_access(text) to authenticated;

alter table public.allowed_users enable row level security;
alter table public.bmi_allowed_users enable row level security;
alter table public.bmi_profiles enable row level security;
alter table public.students enable row level security;
alter table public.schools enable row level security;
alter table public.sbfp_config enable row level security;
alter table public.sbfp_enrolment enable row level security;
alter table public.school_info_sbmi enable row level security;
alter table public.user_presence enable row level security;

create policy "Authenticated users manage allowed users" on public.allowed_users
  for all to authenticated using (true) with check (true);
create policy "Anonymous users read BMI allowlist" on public.bmi_allowed_users
  for select to anon using (true);
create policy "Division manages BMI allowlist" on public.bmi_allowed_users
  for all to authenticated using (public.is_bmi_manager()) with check (public.is_bmi_manager());

create policy "Users create own BMI profile" on public.bmi_profiles
  for insert to authenticated
  with check (
    id = auth.uid()
    and lower(trim(email)) = lower(trim(coalesce(auth.jwt() ->> 'email', '')))
    and (
      lower(trim(email)) like '%@deped.gov.ph'
      or (
        lower(trim(email)) = 'jaybhee84@gmail.com'
        and role = 'division'
      )
      or (
        lower(trim(email)) = 'jl3hee@gmail.com'
        and role = 'school'
      )
    )
  );
create policy "Users read permitted BMI profiles" on public.bmi_profiles
  for select to authenticated using (id = auth.uid() or public.is_bmi_manager());
create policy "Users update permitted BMI profiles" on public.bmi_profiles
  for update to authenticated using (id = auth.uid() or public.is_bmi_manager())
  with check (id = auth.uid() or public.is_bmi_manager());
create policy "Division deletes BMI profiles" on public.bmi_profiles
  for delete to authenticated using (public.is_bmi_manager());

create policy "BMI users read schools" on public.schools
  for select to authenticated using (true);
create policy "BMI users create schools" on public.schools
  for insert to authenticated with check (true);
create policy "BMI users update permitted schools" on public.schools
  for update to authenticated
  using (public.is_bmi_manager() or school_id = public.current_bmi_school_id())
  with check (public.is_bmi_manager() or school_id = public.current_bmi_school_id());

create policy "BMI users read permitted students" on public.students
  for select to authenticated
  using (public.is_bmi_manager() or school_id = public.current_bmi_school_id());
create policy "BMI users create permitted students" on public.students
  for insert to authenticated
  with check (public.is_bmi_manager() or school_id = public.current_bmi_school_id());
create policy "BMI users update permitted students" on public.students
  for update to authenticated
  using (public.is_bmi_manager() or school_id = public.current_bmi_school_id())
  with check (public.is_bmi_manager() or school_id = public.current_bmi_school_id());
create policy "BMI users delete permitted students" on public.students
  for delete to authenticated
  using (public.is_bmi_manager() or school_id = public.current_bmi_school_id());

