create policy "Division creates SBFP config" on public.sbfp_config
  for insert to authenticated with check (public.is_bmi_manager());
create policy "Division updates SBFP config" on public.sbfp_config
  for update to authenticated using (public.is_bmi_manager()) with check (public.is_bmi_manager());

